// One-shot: render Lobe brand marks to static SVG inner markup and emit a
// zero-runtime data module. Run with: bun scripts/bake-provider-marks.mjs
import { writeFileSync } from "node:fs";
import { renderToStaticMarkup } from "react-dom/server";
import React from "react";

const icons = {
    anthropic: ["Anthropic", null],
    bedrock: ["Bedrock", "Color"],
    cerebras: ["Cerebras", "Color"],
    cloudflare: ["Cloudflare", "Color"],
    deepseek: ["DeepSeek", "Color"],
    fireworks: ["Fireworks", "Color"],
    gemini: ["Gemini", "Color"],
    githubcopilot: ["GithubCopilot", null],
    groq: ["Groq", null],
    huggingface: ["HuggingFace", "Color"],
    kimi: ["Kimi", "Color"],
    minimax: ["Minimax", "Color"],
    mistral: ["Mistral", "Color"],
    moonshot: ["Moonshot", null],
    nvidia: ["Nvidia", "Color"],
    openai: ["OpenAI", null],
    opencode: ["OpenCode", null],
    openrouter: ["OpenRouter", "Color"],
    qwen: ["Qwen", "Color"],
    together: ["Together", "Color"],
    vercel: ["Vercel", null],
    xai: ["XAI", null],
    xiaomimo: ["XiaomiMiMo", null],
    zhipu: ["Zhipu", "Color"],
};

const out = {};
for (const [key, [name, variant]] of Object.entries(icons)) {
    const mod = await import(`@lobehub/icons/es/${name}/components/${variant ?? "Mono"}`);
    const Icon = mod.default;
    const svg = renderToStaticMarkup(React.createElement(Icon, { size: 24 }));
    const viewBox = /viewBox="([^"]+)"/.exec(svg)?.[1] ?? "0 0 24 24";
    let body = svg.replace(/^<svg[^>]*>/, "").replace(/<\/svg>$/, "");
    // Drop <title> (decorative here; tiles are aria-hidden) and bake any
    // generated gradient ids into stable ones.
    body = body.replace(/<title>.*?<\/title>/, "");
    out[key] = { viewBox, body };
}

const header = `// GENERATED by scripts/bake-provider-marks.mjs — do not edit by hand.\n// Brand marks from @lobehub/lobe-icons (MIT). Static gradient ids are\n// intentional: the definitions are identical wherever a mark renders.\n\nexport type ProviderMark = { viewBox: string; body: string };\n\nexport const PROVIDER_MARKS: Record<string, ProviderMark> = `;
writeFileSync(
    new URL("../src/components/provider-marks.ts", import.meta.url),
    header + JSON.stringify(out, null, 4) + "\n",
);
console.log("baked", Object.keys(out).length, "marks");
